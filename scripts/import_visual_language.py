"""Import the owner's design archive as data, never execute its Python/JS.

The runtime subset contains vector geometry, labels and tokens, not demo weather,
profiles or command results. Original screens remain explicitly illustrative.
"""
import argparse
import hashlib
import json
import re
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parents[1]
PREFIX = 'GoBot_Design_System/'


def vector(source):
    root = ET.fromstring(source)
    paths = []
    for node in root.iter():
        tag = node.tag.split('}')[-1]
        if tag not in {'svg', 'path'}:
            raise ValueError('Runtime vector has unsupported element: ' + tag)
        if any(k.lower().startswith('on') or 'href' in k.lower() or 'url(' in v.lower() for k, v in node.attrib.items()):
            raise ValueError('Active SVG content')
        if tag == 'path':
            paths.append(dict(node.attrib))
    return {'viewBox': [float(v) for v in root.attrib['viewBox'].split()], 'paths': paths}


def import_archive(path):
    target = ROOT / 'design/visual-language'
    target.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(path) as archive:
        entries = archive.infolist()
        if sum(i.file_size for i in entries) > 30_000_000:
            raise ValueError('Archive expansion limit')
        for item in entries:
            name = PurePosixPath(item.filename)
            if name.is_absolute() or '..' in name.parts or not item.filename.startswith(PREFIX) or '\\' in item.filename:
                raise ValueError('Unsafe archive path')
        data = json.loads(archive.read(PREFIX + 'design-data.json'))
        assert len(data['faces']) == 72 and len(data['icons']) == 109
        screens = [s for group in data['groups'] for s in group['screens']]
        assert len(screens) == 192
        # Retain editable sources and the unexecuted Figma importer. Preview PNGs
        # and package build scripts are not runtime dependencies.
        imported = {}
        for item in entries:
            rel = item.filename[len(PREFIX):]
            if item.is_dir() or not (rel.startswith(('screens/', 'faces/', 'icons/', 'boards/', 'figma-plugin/')) or rel in {
                'STYLEGUIDE.md', 'README.md', 'GoBot_Visual_Atlas.html', 'tokens.json', 'scenario-manifest.json', 'design-data.json',
                'docs/FONT_AWESOME_LICENSE.txt', 'docs/PUBLICATION_STATUS.json',
            }):
                continue
            blob = archive.read(item)
            if rel.endswith('.svg'):
                # Full reference boards contain text/groups; still reject active
                # or externally loaded content before keeping them in the repo.
                if re.search(rb'<(?:script|foreignObject)|\bon\w+\s*=|href\s*=|url\((?!#[a-zA-Z0-9_-]+\))', blob, re.I):
                    raise ValueError('Active reference SVG: ' + rel)
                for element in ET.fromstring(blob).iter():
                    if element.tag.split('}')[-1] not in {'svg','g','defs','clipPath','rect','circle','ellipse','path','line','polyline','polygon','text','tspan'}:
                        raise ValueError('Unsupported reference SVG element')
            dest = target / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(blob)
            imported[rel] = hashlib.sha256(blob).hexdigest()
        runtime = {
            'version': data['version'], 'colors': data['colors'],
            'tokens': json.loads(archive.read(PREFIX + 'tokens.json')),
            'faces': {}, 'icons': {name: vector(svg) for name, svg in data['icons'].items()},
            'expressions': [], 'layouts': sorted({s['layout'] for s in screens}),
        }
        for face in data['faces']:
            nodes = []
            for original in face['nodes']:
                node = dict(original)
                if node['kind'] not in {'rect', 'ellipse', 'svg'}:
                    raise ValueError('Unsupported face primitive')
                if node['kind'] == 'svg':
                    node['vector'] = vector(node.pop('svg'))
                nodes.append(node)
            runtime['faces'][face['id']] = nodes
            if face['skin'] == 'classic':
                runtime['expressions'].append({'id': face['emotion'], 'label': face['label']})
        dist = ROOT / 'services/phone/dist'
        (dist / 'design-data.js').write_text(
            '/* Generated by scripts/import_visual_language.py. Font Awesome Free 6.7.2, CC BY 4.0. */\n'
            'window.GoBotDesignData=' + json.dumps(runtime, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
        reference = {'version': data['version'], 'groups': [{'id': g.get('id', g['screens'][0]['category']), 'label': g.get('title', g['screens'][0]['category_name'])} for g in data['groups']], 'screens': []}
        for screen in screens:
            matches = list((target / 'screens').glob(screen['id'] + '*.svg'))
            if len(matches) != 1:
                raise ValueError('Ambiguous screen SVG: ' + screen['id'])
            reference['screens'].append({k: screen[k] for k in ['id', 'category', 'title', 'layout']})
            reference['screens'][-1]['svg'] = matches[0].read_text(encoding='utf-8')
        (dist / 'design-reference.js').write_text('/* Illustrative screens, not live capabilities. */\nwindow.GoBotDesignReference=' + json.dumps(reference, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
        manifest = {'version': data['version'], 'archive_sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
                    'screen_count': len(screens), 'face_count': len(data['faces']), 'icon_count': len(data['icons']),
                    'layout_count': len(runtime['layouts']), 'demo_data_is_not_capability': True,
                    'figma_import_verified': False,
                    'files': [{'sha256': digest, 'path': rel} for rel, digest in imported.items()]}
        (target / 'import-manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
        print(json.dumps({k: v for k, v in manifest.items() if k != 'files'}))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('archive', type=Path)
    import_archive(parser.parse_args().archive)
